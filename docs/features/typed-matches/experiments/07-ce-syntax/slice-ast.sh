#!/bin/sh
# Emulates option (c): cuts `module internal PatternAst` out of the real src/core/Path.fs into a
# standalone file, as a `src/core/PatternAst.fs` would look after the extraction. The merged code
# byte for byte, dedented by 4 and given a top-level module header plus the Specificity alias.
# Run from anywhere: sh slice-ast.sh
here=$(cd "$(dirname "$0")" && pwd)
src="$here/../../../../../src/core/Path.fs"
out="$here/generated/PatternAst.fs"
mkdir -p "$here/generated"
{
  echo "// GENERATED by slice-ast.sh from src/core/Path.fs - do not edit"
  echo "module internal Xake.PatternAst"
  echo
  echo "open System.Text.RegularExpressions"
  echo
  echo "type Specificity = int * int * int"
  echo
  awk '/^module internal PatternAst =/{on=1; next} /^module internal matchImpl/{on=0} on' "$src" \
    | sed -e 's/^    //'
} > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
